#!/usr/bin/env python3
"""Merge the prototype's original stylesheets into css/legacy.css.

Hard-coded colours become theme tokens (so dark mode reaches every legacy
component) and !important flags are dropped: cascade layers in css/tabi.css
now decide precedence. Re-run after editing _original/*.css.
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ['style.css', 'readability.css', 'stay-planner.css']

TEXT = {
    '#173746': '--ink', '#183a48': '--ink', '#233f4b': '--ink',
    '#3b515b': '--muted', '#536971': '--muted', '#596a70': '--muted', '#586f75': '--muted', '#667575': '--muted',
    '#49634e': '--green', '#4e706a': '--green', '#667d69': '--green',
    '#90402b': '--accent-ink', '#964237': '--accent-ink', '#a44732': '--accent-ink', '#a74d3b': '--accent-ink',
    '#a92c1c': '--danger', '#9b3b27': '--accent-ink', '#8f5f2f': '--warn-ink', '#6c8486': '--muted',
    'white': '--on-accent', '#fff': '--on-accent',
}
BG = {
    'white': '--surface', '#fff': '--surface', '#fffefa': '--surface',
    '#f8f7f2': '--paper', '#f6f4ed': '--paper',
    '#eef1ec': '--surface-2', '#edf0e8': '--surface-2', '#e9eee4': '--surface-2', '#e7eee4': '--surface-2',
    '#eaf0ed': '--surface-2', '#e0e9e0': '--surface-2',
    '#c3d7ce': '--tint-strong', '#b9c9c1': '--tint-strong',
    '#f7e8de': '--accent-light', '#285263': '--ink-2', '#9b3b27': '--accent-hover',
    '#153b4870': '--backdrop',
}
LINE = {c: '--line' for c in ['#cbd5c5', '#ced8cb', '#d5decd', '#d9ded6', '#d9dfd7', '#d8dfd8', '#dce3d5', '#e1e5df', '#e5e8e0', '#ccc']}
LINE.update({c: '--line-strong' for c in ['#a8b9b1', '#b7c8b1', '#b9c7c3']})
LINE.update({'#d3b8b0': '--accent-line', '#a74d3b': '--accent'})
SVG = {'#cddbcf': '--map-land', '#b9cdbf': '--map-coast', '#4e706a': '--muted', '#6c8486': '--muted', '#667d69': '--green', 'white': '--surface'}

COLOR_RE = re.compile(r'#[0-9a-fA-F]{3,8}\b|(?<![-\w])white\b')

def table(prop):
    if prop.startswith('--'):
        return None  # legacy token definitions stay; the app layer redefines them
    if prop in ('fill', 'stroke'):
        return SVG
    if prop.startswith('background'):
        return BG
    if prop.startswith('border') or prop.startswith('outline'):
        return LINE
    if prop in ('color', 'caret-color', 'text-decoration-color'):
        return TEXT
    return None

def convert_decl(match):
    prop, value = match.group(1), match.group(2)
    mapping = table(prop.strip().lower())
    if mapping:
        value = COLOR_RE.sub(lambda m: f'var({mapping[m.group(0).lower()]})' if m.group(0).lower() in mapping else m.group(0), value)
    value = value.replace('!important', '').rstrip()
    return f'{prop}:{value}'

out = []
HEADER = '/* GENERATED by tools/build-legacy-css.py from _original/*.css. Do not edit by hand. */\n'
for name in SOURCES:
    css = (root / '_original' / name).read_text()
    css = re.sub(r'([a-zA-Z-]+)\s*:\s*([^;{}]+)', convert_decl, css)
    out.append(f'/* ---- {name} ---- */\n{css}')
(root / 'css' / 'legacy.css').write_text(HEADER + '@layer legacy{\n' + '\n'.join(out) + '\n}\n')
left = COLOR_RE.findall((root / 'css' / 'legacy.css').read_text())
print('legacy.css written;', len(left), 'literal colours left:', sorted(set(c.lower() for c in left)))
